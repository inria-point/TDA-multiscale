A4 = (8.27, 11.69)
INK = "#1a1a1a"
GREY = "#666666"
ACCENT = "#a63603"


def page(pdf, title, body, image=None, caption=None, subtitle=None,
         img_frac=0.52):
    """One page: heading, wrapped body text, and a figure under it."""
    fig = plt.figure(figsize=A4)
    fig.patch.set_facecolor("white")
    y = 0.955
    fig.text(0.07, y, title, fontsize=17, color=INK, va="top", weight="bold")
    y -= 0.033
    if subtitle:
        fig.text(0.07, y, subtitle, fontsize=10.5, color=ACCENT, va="top")
        y -= 0.024
    y -= 0.012
    for para in body:
        if para.startswith("•"):
            wrapped = textwrap.wrap(para[1:].strip(), 92)
            for j, line in enumerate(wrapped):
                fig.text(0.085 if j else 0.075, y,
                         ("• " if j == 0 else "") + line, fontsize=9.8,
                         color=INK, va="top")
                y -= 0.0175
            y -= 0.004
        elif para.startswith("`"):
            for line in para.strip("`").split("\n"):
                fig.text(0.075, y, line, fontsize=8.6, color="#333",
                         va="top", family="monospace")
                y -= 0.0155
            y -= 0.006
        else:
            for line in textwrap.wrap(para, 95):
                fig.text(0.07, y, line, fontsize=9.8, color=INK, va="top")
                y -= 0.0175
            y -= 0.008
    if image:
        path = os.path.join(FIG, image)
        if os.path.exists(path):
            img = mpimg.imread(path)
            h, w = img.shape[:2]
            top = y - 0.015
            cap_lines = textwrap.wrap(caption, 108) if caption else []
            # the caption needs its own room, or a wide figure pushes it off
            cap_h = 0.016 * len(cap_lines) + (0.012 if cap_lines else 0)
            avail_h = top - 0.05 - cap_h
            box_w = 0.94
            page_ar = A4[0] / A4[1]
            want_h = box_w * (h / w) * page_ar
            if want_h > avail_h:
                box_w *= avail_h / want_h
                want_h = avail_h
            # centre the block in whatever room is left rather than hanging it
            # from the text, so a short wide figure does not float
            bottom = 0.05 + cap_h + (avail_h - want_h) / 2
            ax = fig.add_axes([(1 - box_w) / 2, bottom, box_w, want_h])
            ax.imshow(img)
            ax.axis("off")
            cy = bottom - 0.014
            for line in cap_lines:
                fig.text(0.5, cy, line, fontsize=8.2, color=GREY,
                         ha="center", va="top")
                cy -= 0.016
    pdf.savefig(fig)
    plt.close(fig)


