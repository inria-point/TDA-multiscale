    # 0.40 is past the point where the blobs merge and the arrangement stops
    # being "centres plus cells"; plotting it would contradict the caption
    D = D[D["радиус"] <= 0.32]
    g = D.groupby("радиус")[["крупный", "мелкий", "средний"]].mean()
    fig, ax = plt.subplots(figsize=(9, 4.4))
    for c, col in [("крупный", "#a63603"), ("мелкий", "#08306b"),
                   ("средний", "#7f7f7f")]:
        ax.plot(g.index, g[c], "o-", color=col, label=c, lw=2)
    top = ax.get_ylim()[1]
    for x, lab in [(0.232, "как в тексте"), (0.271, "как в перемешанном")]:
        ax.axvline(x, color="#999", ls="--", lw=1)
        ax.annotate(lab, (x, top), (-4, -8), textcoords="offset points",
                    fontsize=8.5, color="#666", ha="right", va="top",
                    rotation=90)
    ax.set_xlabel("радиус комка / средняя парная дистанция")
    ax.set_ylabel("полоса (d)")
    ax.set_title("Меняется только радиус комка, всё остальное фиксировано",
                 fontsize=11)
    ax.legend(fontsize=9)
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, "synthetic_inflate.png"), dpi=150)
    plt.close(fig)
