"""Assemble the session's findings into a PDF with the figures.

There is no pandoc or LaTeX on this machine, so the pages are laid out directly
with matplotlib: a title, a body of wrapped text, and one figure per page read
back from figures/. Nothing is recomputed here -- every number quoted is one
that appears in results/GEOMETRY.md and came out of the scripts named on the
page, so this file is a presentation layer and not a source of results.
"""
